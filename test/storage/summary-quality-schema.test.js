'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { FORMAL_AGENT_MIGRATIONS } = require('../../src/runtime/storage-worker/schema')
const { SqliteSubtitleStore } = require('../../src/runtime/storage-worker/subtitle-store')
const { ModelAccessStore } = require('../../src/runtime/storage-worker/model-access-store')
const { presetForIdentity } = require('../../src/agent/model-access/preset-registry')

test('SEM-T08/F33/F39/DB1/J25/J31-COMPAT: v33 appends idempotently and retains chosen model, old strategy and capabilities', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'summary-quality-migration-'))
  const file = path.join(root, 'state.sqlite3')
  let subtitles
  t.after(() => { subtitles?.close(); fs.rmSync(root, { recursive: true, force: true }) })
  const open = migrations => {
    subtitles = new SqliteSubtitleStore({ databasePath: file, migrations })
    return new ModelAccessStore({ subtitleStore: subtitles })
  }
  let models = open(FORMAL_AGENT_MIGRATIONS.slice(0, 32))
  const command = value => models.configure({ command: { ...value, expectedRevision: models.revision() } })
  command({ type: 'createProfile', profileId: 'preset.deepseek-openai', label: 'DeepSeek', httpsOrigin: 'https://api.deepseek.com', basePath: '/' })
  command({ type: 'addModel', profileId: 'preset.deepseek-openai', modelId: 'deepseek-v4-flash', capabilities: presetForIdentity('deepseek-openai@1').capabilities })
  command({ type: 'assignPurpose', purpose: 'default', target: { profileId: 'preset.deepseek-openai', modelId: 'deepseek-v4-flash' } })
  const prefix = subtitles.database.prepare('SELECT version,checksum FROM schema_migrations').all()
  const oldCatalog = models.internalCatalog()
  subtitles.close(); models = open(FORMAL_AGENT_MIGRATIONS)
  assert.deepEqual(models.internalCatalog(), oldCatalog)
  assert.deepEqual(subtitles.database.prepare('SELECT version,checksum FROM schema_migrations WHERE version<=32').all(), prefix)
  const assignments = () => subtitles.database.prepare('SELECT purpose,profile_id,model_id FROM agent_model_purpose_assignments ORDER BY purpose').all()
  const before = assignments()
  command({ type: 'addModel', profileId: 'preset.deepseek-openai', modelId: 'deepseek-flash', capabilities: presetForIdentity('deepseek-openai@2').capabilities })
  assert.deepEqual(assignments(), before)
  const profile = models.internalCatalog().profiles.find(item => item.profile_id === 'preset.deepseek-openai')
  assert.equal(profile.models.find(item => item.modelId === 'deepseek-v4-flash').request_strategy, 'deepseek-openai@1')
  assert.equal(profile.models.find(item => item.modelId === 'deepseek-flash').request_strategy, 'deepseek-openai@2')
  const oldRow = subtitles.database.prepare('SELECT preset_identity,request_strategy,strategy_version FROM agent_model_profile_models WHERE model_id=?').get('deepseek-flash')
  assert.deepEqual({ ...oldRow }, { preset_identity: null, request_strategy: 'openai-compatible@1', strategy_version: 1 })
  const catalog = models.internalCatalog()
  subtitles.close(); models = open(FORMAL_AGENT_MIGRATIONS)
  assert.deepEqual(models.internalCatalog(), catalog)
  assert.equal(subtitles.database.prepare('SELECT COUNT(*) AS count FROM schema_migrations').get().count, 33)
  assert.equal(subtitles.database.prepare('PRAGMA foreign_key_check').all().length, 0)
})
